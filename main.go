// Package main boots the Fitness Tracker API server.
//
// @title           Fitness Tracker API
// @version         3.0
// @description     API matching the current FitnessTracker Swift app. GET /trainings returns [Workout]; POST accepts CreateWorkoutRequest with sessions: [Workout]. Weight and reps are optional integers.
//
// @securityDefinitions.apikey BearerAuth
// @in header
// @name Authorization
// @description  Provide your JWT with the "Bearer " prefix. Example: "Bearer {token}".
package main

import (
	"fmt"
	"log"
	"os"
	"strings"
	"time"

	"github.com/gin-contrib/cors"
	"github.com/gin-gonic/gin"
	"gorm.io/driver/postgres"
	"gorm.io/gorm"

	"github.com/VibeTeam/fitness-tracker-backend/shared/middleware"
	"github.com/VibeTeam/fitness-tracker-backend/user/auth"
	userhandler "github.com/VibeTeam/fitness-tracker-backend/user/handler"
	"github.com/VibeTeam/fitness-tracker-backend/user/repository/gormrepository"
	"github.com/VibeTeam/fitness-tracker-backend/user/use_case"

	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"

	_ "fitness-tracker-backend/docs"

	"github.com/VibeTeam/fitness-tracker-backend/llm/suggester"
	workouthandler "github.com/VibeTeam/fitness-tracker-backend/workout/handler"
	workoutrepo "github.com/VibeTeam/fitness-tracker-backend/workout/repository/gormrepository"
)

func main() {
	accessSecret, refreshSecret, err := jwtSecretsFromEnv()
	if err != nil {
		log.Fatalf("invalid JWT configuration: %v", err)
	}

	databaseURL := os.Getenv("DATABASE_URL")
	if databaseURL == "" {
		// local fallback
		databaseURL = "host=localhost port=5432 user=postgres password=postgres dbname=fitness_tracker sslmode=disable"
	}

	database, err := gorm.Open(postgres.Open(databaseURL), &gorm.Config{})
	if err != nil {
		log.Fatalf("failed to connect database: %v", err)
	}

	// Schema provisioning is managed separately from server startup.

	// build dependencies
	userRepository := gormrepository.NewUserRepository(database)

	// JWT setup

	tokenManager := auth.NewManager(accessSecret, refreshSecret, 15*time.Minute, 7*24*time.Hour)
	authService := use_case.NewAuthService(userRepository, tokenManager)

	// repositories for workout domain
	muscleGroupRepo := workoutrepo.NewMuscleGroupRepository(database)
	workoutTypeRepo := workoutrepo.NewWorkoutTypeRepository(database)
	trainingRepo := workoutrepo.NewTrainingRepository(database)
	workoutSessionRepo := workoutrepo.NewWorkoutSessionRepository(database)

	// handlers
	authMiddleware := middleware.Auth(tokenManager)

	userHandler := userhandler.New(userRepository)
	authHandler := userhandler.NewAuthHandler(authService)

	mgHandler := workouthandler.NewMuscleGroupHandler(muscleGroupRepo)
	wtHandler := workouthandler.NewWorkoutTypeHandler(workoutTypeRepo)
	trainingHandler := workouthandler.NewTrainingHandler(trainingRepo, workoutTypeRepo)
	profileStatsHandler := workouthandler.NewProfileStatsHandler(trainingRepo, workoutSessionRepo)

	llmBaseURL := os.Getenv("GROQ_BASE_URL")
	if llmBaseURL == "" {
		llmBaseURL = "https://api.groq.com/openai/v1"
	}
	modelName := os.Getenv("GROQ_MODEL")
	if modelName == "" {
		modelName = "llama-3.1-8b-instant"
	}
	llmAPIKey := os.Getenv("GROQ_API_KEY")

	llmClient := suggester.New(llmBaseURL, modelName, llmAPIKey)
	suggestHandler := workouthandler.NewSuggestHandler(trainingRepo, llmClient)
	var coach workouthandler.ProfileCoach
	if llmAPIKey != "" {
		coach = llmClient
	}
	profileHandler := workouthandler.NewProfileHandler(trainingRepo, coach)

	router := gin.Default()

	// Configure CORS middleware
	corsConfig := cors.DefaultConfig()
	corsOrigins := splitEnvList("CORS_ALLOWED_ORIGINS")
	if len(corsOrigins) == 0 {
		corsConfig.AllowAllOrigins = true
	} else {
		corsConfig.AllowOrigins = corsOrigins
	}
	corsConfig.AllowMethods = []string{"GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"}
	corsConfig.AllowHeaders = []string{"Origin", "Content-Type", "Accept", "Authorization"}
	router.Use(cors.New(corsConfig))
	router.GET("/healthz", func(c *gin.Context) {
		c.JSON(200, gin.H{"status": "ok"})
	})

	// register routes
	userHandler.RegisterRoutes(router, authMiddleware)
	authHandler.RegisterRoutes(router, authMiddleware)

	mgHandler.RegisterRoutes(router, authMiddleware)
	wtHandler.RegisterRoutes(router, authMiddleware)
	trainingHandler.RegisterRoutes(router, authMiddleware)
	profileStatsHandler.RegisterRoutes(router, authMiddleware)
	profileHandler.RegisterRoutes(router, authMiddleware)
	suggestHandler.RegisterRoutes(router, authMiddleware)
	router.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler)) // Autogenerated swagger docs

	listenAddr := ":8080"
	if p := os.Getenv("PORT"); p != "" {
		listenAddr = ":" + p
	}

	log.Printf("Starting server at %s", listenAddr)
	log.Printf("Swagger is available at http://localhost%s/swagger/doc.json "+
		"or http://localhost%s/swagger/index.html", listenAddr, listenAddr)
	if err := router.Run(listenAddr); err != nil {
		log.Fatalf("server error: %v", err)
	}
}

func splitEnvList(key string) []string {
	raw := os.Getenv(key)
	if raw == "" {
		return nil
	}

	var values []string
	for _, value := range strings.Split(raw, ",") {
		value = strings.TrimSpace(value)
		if value != "" {
			values = append(values, value)
		}
	}
	return values
}

// Validate secrets before connecting to the database. Never include their values in errors.
func jwtSecretsFromEnv() (string, string, error) {
	access := os.Getenv("ACCESS_SECRET")
	refresh := os.Getenv("REFRESH_SECRET")
	for _, entry := range []struct{ name, value string }{
		{"ACCESS_SECRET", access}, {"REFRESH_SECRET", refresh},
	} {
		if strings.TrimSpace(entry.value) == "" {
			return "", "", fmt.Errorf("%s must be set and non-empty", entry.name)
		}
		switch strings.TrimSpace(entry.value) {
		case "access-secret", "refresh-secret":
			return "", "", fmt.Errorf("%s must not use a previously published default", entry.name)
		}
	}
	return access, refresh, nil
}
